export type Key = keyof typeof en;
export const dictionaries = { en, "zh-Hans": hans, "zh-Hant": hant };
export function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem("invisi.language");
    if (saved && saved in dictionaries) return saved as Language;
  } catch {}
  const l = navigator.language;
  return /zh.*(Hant|TW|HK|MO)/i.test(l)
    ? "zh-Hant"
    : /^zh/i.test(l)
      ? "zh-Hans"
      : "en";
}
